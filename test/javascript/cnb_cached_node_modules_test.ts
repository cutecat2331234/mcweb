import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'
import test from 'node:test'

const source = (path: string) => readFileSync(resolve(process.cwd(), path), 'utf8')
const helperPath = 'scripts/attach-cnb-cached-node-modules.sh'
const helper = source(helperPath)
const config = source('.cnb.yml')
const dockerfile = source('deploy/cnb/quality-dependencies.Dockerfile')

test('CNB documentation uses real cached dependency paths through the CE helper', () => {
  assert.ok(config.includes(`bash ${helperPath} /opt/mcweb-quality/docs docs`))
  assert.doesNotMatch(config, /ln\s+-s[^\r\n]*\bdocs\/node_modules/)
  assert.ok(config.includes('test -x docs/node_modules/.bin/astro'))
})

test('cached dependency attachment checks lock identity before creating a real directory', () => {
  assert.ok(helper.includes('for manifest in package.json package-lock.json; do'))
  const compare = helper.indexOf('cmp -- "${workspace_package}/${manifest}" "${cache_package}/${manifest}"')
  const create = helper.indexOf('mkdir -- "${workspace_modules}"')
  const copy = helper.indexOf('cp -a --reflink=auto -- "${cache_modules}/." "${workspace_modules}/"')
  assert.ok(compare !== -1 && compare < create && create < copy)
  assert.ok(helper.includes('[[ ! -d "${cache_modules}" || -L "${cache_modules}" ]]'))
  assert.ok(helper.includes('[[ -e "${workspace_modules}" || -L "${workspace_modules}" ]]'))
  assert.doesNotMatch(helper, /^\s*(?:rm|mv|ln|npm|npx)\s/m)
})

test('dependency installation remains in the Docker cache, not the source helper', () => {
  assert.ok(dockerfile.includes('WORKDIR /opt/mcweb-quality/docs'))
  assert.ok(dockerfile.includes('COPY docs/package.json docs/package-lock.json ./'))
  assert.ok(dockerfile.includes('RUN npm ci --include=dev --no-audit --no-fund'))
  assert.ok(dockerfile.includes('ENV npm_config_offline=true'))
  assert.ok(!dockerfile.includes(helperPath), 'source-only attachment must not invalidate dependency layers')
})
